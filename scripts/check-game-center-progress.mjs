import assert from 'node:assert/strict';
import { createArcade, collectibles } from '../js/leisure/game-center-data.js';
import { progressOf, annualChallenges, challengeProgress, recordArcadeResult, claimChallenge, claimAlbumMilestone, albumCount } from '../js/leisure/game-center-progress.js';
const data = createArcade();
data.plushes.teddy = { count: 1 }; data.collection.sticker = 1;
assert.equal(albumCount(progressOf(data, 30)), 2);
delete data.plushes.teddy;
assert.equal(albumCount(progressOf(data, 30)), 2, 'Gifted plush remains discovered');
assert.equal(annualChallenges(30).length, 3);
assert.notDeepEqual(annualChallenges(30), annualChallenges(31));
assert.equal(claimChallenge(data, 30, 'basket'), null);
const session = { id: 'one', game: 'basketball', score: 22, age: 30 };
assert.equal(recordArcadeResult(data, 30, session, { tickets: 6, win: true }).newBest, true);
assert.equal(recordArcadeResult(data, 30, session), null, 'Duplicate settlement cannot progress');
assert.equal(recordArcadeResult(data, 30, { ...session, id: 'interrupted' }, { interrupted: true }), null);
const restored = JSON.parse(JSON.stringify(data));
assert.equal(recordArcadeResult(restored, 30, session), null, 'Duplicate protection survives reload');
assert.equal(claimChallenge(restored, 30, 'basket').tickets, 6);
assert.equal(claimChallenge(restored, 30, 'basket'), null);
recordArcadeResult(restored, 30, { id: 'two', game: 'whack', score: 40, age: 30 }, { tickets: 10 });
recordArcadeResult(restored, 30, { id: 'three', game: 'cow', score: 99, age: 30 }, { win: true });
assert.equal(claimChallenge(restored, 30, 'variety').tickets, 8);
assert.equal(restored.progress.records.cow.best, 0, 'Decorative cow progress is not a skill score');
const best = restored.progress.records.basketball.best;
progressOf(restored, 31);
assert.equal(restored.progress.annual.plays, 0);
assert.equal(restored.progress.records.basketball.best, best);
recordArcadeResult(restored, 31, { id: 'old-claw', game: 'claw', age: 30 }, { win: true });
assert.equal(restored.progress.annual.plays, 0, 'Last-year resumed claw cannot earn current-year challenge progress');
for (const item of collectibles.slice(0, 3)) restored.progress.album[item.id] = true;
const before = restored.tickets;
assert.equal(claimAlbumMilestone(restored, 31, 'starter').tickets, 8);
assert.equal(restored.tickets, before + 8);
assert.equal(claimAlbumMilestone(restored, 32, 'starter'), null);
assert.equal(claimAlbumMilestone(restored, 32, 'complete'), null);
const annual = progressOf(restored, 30).annual;
annual.scores.basketball = 0; annual.tickets = 14;
assert.equal(challengeProgress({ type: 'tickets', target: 15 }, annual), 14, 'Bonus rewards do not advance earned-ticket missions');
console.log('PASS Game Center progress: legacy gifts; gifted album retention; annual rotation; best scores; complete-only progress; duplicate and reload guards; yearly reset; old-year session; unique album milestones; bonus-ticket isolation');
