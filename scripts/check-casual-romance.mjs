import assert from 'node:assert/strict';
import { createInitialState } from '../js/core/state.js';
import { getRomanceChance, getAcquaintanceChance, getSocialContext } from '../js/stats/appearance-rules.js';
import { createDatingEvent, canStartRelationship } from '../js/relationships/relationships.js';
import { createCasualLifeEvents } from '../js/events/casual-life.js';
const p = { ...createInitialState().player, age: 25, casualLife: true, appearance: 50, gender: 'female', health: 80, happiness: 80, money: 0 };
assert.equal(Number(getRomanceChance(p).toFixed(2)), 0.35);
assert.equal(getRomanceChance({ ...p, casualLife: false }), 0.55);
assert.equal(getSocialContext(p, 26), 'community');
const q = { ...p, purchases: [{ id: 'noodle-cart' }], streetJobs: [{ id: 'noodle-seller', startedAtAge: 25 }] };
assert.equal(getRomanceChance(q), 0.5);
assert.equal(getSocialContext(q, 26), 'work');
assert.equal(getRomanceChance({ ...q, age: 27 }), 0.55);
assert.equal(Number(getRomanceChance({ ...q, age: 27, purchases: [] }).toFixed(2)), 0.35);
assert.ok(getAcquaintanceChance(q, 26) > getAcquaintanceChance(p, 26));
assert.equal(getRomanceChance({ ...p, money: 1_000_000_000 }), getRomanceChance(p));
const rejection = createDatingEvent(p, 25, () => 0.99);
assert.equal(rejection.choices[0].acceptDating, false);
assert.equal(createDatingEvent(p, 25, () => 0).choices[0].acceptDating, true);
assert.deepEqual(JSON.parse(JSON.stringify(rejection)).choices, rejection.choices);
assert.equal(canStartRelationship({ ...p, casualService: { releaseAge: 27 } }), false);
assert.ok(createCasualLifeEvents(27, p).some(e => e.id === 'casual-romance-27'));
const coupled = { ...p, partner: { id: 'partner', name: 'An', relationship: 70 } };
const stories = createCasualLifeEvents(28, coupled);
assert.ok(stories.some(e => e.id === 'casual-couple-plans'));
assert.equal(coupled.partner.relationship, 70);
console.log('PASS: chance by current work; recovery after two years; no wealth penalty; social contexts; rejection and acceptance; persisted result; service; single and couple stories');
