import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createGameServer } from '../server/account-server.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH ?? 'C:/Users/Admin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const db = { accounts: [], sessions: [], starts: [], runs: [] };
let revision = 0;
const storage = { async load() { return { revision, payload: structuredClone(db) }; }, async save(next) { Object.assign(db, structuredClone(next)); return ++revision; } };
const ids = [];
const server = createGameServer({ dataFile: null, storage, adminAccountIds: ids });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const register = async (username, nickname) => (await fetch(base+'/api/account/register', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username, nickname, password: 'test-password' }) })).json();
const owner = await register('owner', 'Chủ dự án'); ids.push(owner.user.id);
await register('player', '<script>Người chơi</script>');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base+'/admin');
  await page.getByLabel('Tên đăng nhập').fill('owner');
  await page.getByLabel('Mật khẩu').fill('test-password');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await page.getByText('@player', { exact: true }).waitFor();
  assert.equal(await page.locator('#accounts script').count(), 0);
  await page.getByRole('button', { name: 'Khóa', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await page.getByText('Đã khóa', { exact: true }).waitFor();
  assert.equal(db.accounts.find(item => item.username === 'player').disabled, true);
  await page.getByRole('button', { name: 'Mở khóa', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await page.getByText('Hoạt động', { exact: true }).waitFor();
  await page.getByLabel('Tìm người chơi').fill('owner');
  await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('accounts').rows.length === 1);
  assert.equal(await page.getByRole('button', { name: 'Khóa', exact: true }).count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'output/admin-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await page.getByLabel('Tên đăng nhập').waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS admin UI: login; list; escaped names; lock/unlock confirmation; search; owner protection; mobile layout; logout');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
